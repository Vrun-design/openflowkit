// Writes src/services/shapeLibrary/providerIconManifest.ts: every bundled provider icon, by provider and
// category, so the editor knows the catalog without bundling a loader per icon. Re-run after adding or
// removing an SVG under assets/third-party-icons/*/processed (providerIconManifest.test.ts fails until you do).
// node scripts/gen-icon-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const ICONS = path.join(ROOT, 'assets/third-party-icons');
const OUT = path.join(ROOT, 'src/services/shapeLibrary/providerIconManifest.ts');

/** provider → category → icon paths under the category, without `.svg`; sorted, so the file is stable. */
export function readIconManifest(iconsDir = ICONS) {
  const manifest = {};
  for (const provider of fs.readdirSync(iconsDir).sort()) {
    const processed = path.join(iconsDir, provider, 'processed');
    if (!fs.existsSync(processed)) continue;
    const categories = {};
    for (const file of fs.readdirSync(processed, { recursive: true }).map(String).sort()) {
      if (!file.endsWith('.svg')) continue;
      const parts = file.slice(0, -'.svg'.length).split(path.sep);
      const [category, name] = parts.length > 1 ? [parts[0], parts.slice(1).join('/')] : ['', parts[0]];
      (categories[category] ??= []).push(name);
    }
    if (Object.keys(categories).length) manifest[provider] = categories;
  }
  return manifest;
}

export function renderIconManifest(manifest) {
  const lines = Object.entries(manifest).map(([provider, categories]) => [
    `  ${JSON.stringify(provider)}: {`,
    ...Object.entries(categories).map(([category, names]) => `    ${JSON.stringify(category)}: ${JSON.stringify(names)},`),
    '  },',
  ].join('\n'));
  return `// Generated by scripts/gen-icon-manifest.mjs from assets/third-party-icons/*/processed. Do not edit.
// provider → category → icon path under the category (without .svg).
export const PROVIDER_ICON_MANIFEST: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = {
${lines.join('\n')}
};
`;
}

if (process.argv[1] === import.meta.filename) {
  fs.writeFileSync(OUT, renderIconManifest(readIconManifest()));
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
