import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const base = process.env.V2_BASE_URL ?? 'http://127.0.0.1:4191';
const evidence = 'docs/evidence/v2-polish';
fs.mkdirSync(evidence, { recursive: true });
const browser = await chromium.launch({ args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const state = () => page.evaluate(() => window.__V2__.getState());
const doc = () => page.evaluate(() => window.__V2__.getDocument());
const rect = (id) => page.evaluate((id) => window.__V2__.getNodeRect(id), id);
try {
  await page.goto(`${base}/#/v2/polish-${Date.now()}`);
  await page.waitForFunction(() => window.__V2__?.getState());
  await page.locator('canvas').waitFor();
  await page.getByTestId('v2-canvas').focus();
  await page.keyboard.press('r');
  await page.mouse.click(500, 400);
  await page.waitForFunction(() => window.__V2__.getState().nodes.length === 1);
  const id = (await state()).nodes[0];
  assert.deepEqual((await state()).selectedNodes, [id]);
  assert.equal((await state()).tool, 'select');
  await page.waitForTimeout(300);
  const idleBefore = await page.evaluate(() => window.__V2__.getRenderDiagnostics());
  await page.waitForTimeout(300);
  const idleAfter = await page.evaluate(() => window.__V2__.getRenderDiagnostics());
  assert.equal(idleAfter.renderCount, idleBefore.renderCount, 'dot grid must not render at idle');
  assert.equal(idleAfter.continuousTickerRunning, false);
  const before = (await doc()).pages[0].nodes[0];
  const bounds = await rect(id);
  const barBefore = await page.getByRole('toolbar', { name: 'Selection actions' }).boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 71, bounds.y + bounds.height / 2 + 43, { steps: 12 });
  await page.waitForTimeout(100);
  const barDuring = await page.getByRole('toolbar', { name: 'Selection actions' }).boundingBox();
  assert.ok(Math.abs(barDuring.x - barBefore.x - 71) < 2, 'context bar must follow drag');
  await page.screenshot({ path: `${evidence}/drag.png` });
  await page.mouse.up();
  await page.waitForFunction(() => window.__V2__.getState().revision === 2);
  const after = (await doc()).pages[0].nodes[0];
  assert.ok(Math.abs(after.transform.translation.x - before.transform.translation.x - 71) < 0.01);
  // A second drag immediately after committing must keep working.
  const moved = await rect(id);
  await page.mouse.move(moved.x + 40, moved.y + 25);
  await page.mouse.down();
  await page.mouse.move(moved.x + 57, moved.y + 34, { steps: 4 });
  await page.mouse.up();
  await page.waitForFunction(() => window.__V2__.getState().revision === 3);
  const beforeResize = (await doc()).pages[0].nodes[0];
  const resizeRect = await rect(id);
  // Stay one screen pixel inside the 14px handle hit target. Exact fractional
  // canvas edges can round to the adjacent backing-store pixel under SwiftShader.
  const resizeHandle = {
    x: resizeRect.x + resizeRect.width - 1,
    y: resizeRect.y + resizeRect.height - 1,
  };
  await page.mouse.move(resizeHandle.x, resizeHandle.y);
  await page.mouse.down();
  await page.mouse.move(resizeHandle.x + 32, resizeHandle.y + 24, { steps: 8 });
  await page.mouse.up();
  await page.waitForFunction(() => window.__V2__.getState().revision === 4);
  const resizedNode = (await doc()).pages[0].nodes[0];
  const resizedRect = await rect(id);
  // Canonical transforms preserve intrinsic size and resize through scale.
  assert.ok(resizedNode.transform.scale.x > beforeResize.transform.scale.x);
  assert.ok(resizedRect.width - resizeRect.width > 30);
  const beforeCancel = await doc();
  const cancelRect = await rect(id);
  await page.mouse.move(cancelRect.x + 40, cancelRect.y + 30);
  await page.mouse.down();
  await page.mouse.move(cancelRect.x + 120, cancelRect.y + 90, { steps: 4 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  assert.deepEqual(await doc(), beforeCancel);
  await page.getByRole('button', { name: /^Fill:/ }).click();
  await page.getByRole('button', { name: '#c9b8ed', exact: true }).click();
  await page.waitForFunction(() => window.__V2__.getDocument().pages[0].nodes[0].appearance.fill === '#c9b8ed');
  assert.deepEqual((await state()).selectedNodes, [id]);
  const colorRevision = (await state()).revision;
  await page.getByRole('slider', { name: 'Hue', exact: true }).focus();
  await page.keyboard.press('PageUp');
  await page.waitForTimeout(250);
  assert.ok((await state()).revision > colorRevision, 'keyboard color edit commits history');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: /^Stroke:/ }).click();
  await page.getByRole('radio', { name: 'Dashed', exact: true }).check();
  await page.getByRole('spinbutton', { name: 'Stroke width', exact: true }).fill('3');
  await page.getByRole('spinbutton', { name: 'Stroke width', exact: true }).press('Enter');
  await page.waitForTimeout(250);
  const popover = await page.getByRole('dialog', { name: 'Stroke', exact: true }).boundingBox();
  assert.ok(popover.y >= 8 && popover.y + popover.height <= 892, 'stroke popover fits viewport');
  await page.screenshot({ path: `${evidence}/stroke.png` });
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  assert.equal((await doc()).pages[0].nodes[0].appearance.strokeWidth, 3);
  await page.getByTestId('v2-canvas').focus();
  await page.keyboard.press('ControlOrMeta+z');
  await page.waitForFunction(() => window.__V2__.getDocument().pages[0].nodes[0].appearance.strokeWidth === 1.5);
  await page.keyboard.press('ControlOrMeta+Shift+z');
  await page.waitForFunction(() => window.__V2__.getDocument().pages[0].nodes[0].appearance.strokeWidth === 3);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('radio', { name: 'Dark', exact: true }).check();
  await page.waitForTimeout(250);
  const darkText = await page.getByRole('button', { name: 'Export', exact: true }).evaluate((element) => getComputedStyle(element).color);
  assert.equal(darkText, 'rgb(241, 242, 236)');
  await page.screenshot({ path: `${evidence}/dark-settings.png` });
  await page.getByRole('radio', { name: 'Light', exact: true }).check();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByTitle('Rename diagram').click();
  const title = page.getByRole('textbox', { name: 'Diagram title', exact: true });
  await title.fill('Payments architecture');
  await title.press('Enter');
  await page.waitForFunction(() => window.__V2__.getDocument().name === 'Payments architecture');
  await page.getByTitle('Canvas background').click();
  await page.getByRole('button', { name: '#f5f1e8', exact: true }).click();
  await page.waitForTimeout(100);
  assert.equal(await page.getByTestId('v2-editor').evaluate((element) => getComputedStyle(element).backgroundColor), 'rgb(245, 241, 232)');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Connector', exact: true }).click();
  const connectorRevision = (await state()).revision;
  await page.mouse.move(280, 260);
  await page.mouse.down();
  await page.mouse.move(680, 520, { steps: 8 });
  await page.mouse.up();
  await page.waitForFunction((revision) => window.__V2__.getState().revision > revision, connectorRevision);
  assert.ok((await state()).selectedConnector, 'new free arrow must be selected');
  await page.mouse.click(480, 390);
  assert.ok((await state()).selectedConnector, 'free arrow must remain selectable');
  const arrowBefore = (await doc()).pages[0].connectors.at(-1);
  await page.mouse.move(680, 520);
  await page.mouse.down();
  await page.mouse.move(760, 580, { steps: 5 });
  await page.mouse.up();
  await page.waitForTimeout(150);
  const arrowAfter = (await doc()).pages[0].connectors.at(-1);
  assert.notDeepEqual(arrowAfter.target, arrowBefore.target, 'free arrow endpoint must be draggable');
  await page.screenshot({ path: `${evidence}/light.png` });
  const savedAppearance = (await doc()).pages[0].nodes[0].appearance;
  await page.waitForFunction(() => window.__V2__.getState().save === 'saved');
  await page.reload();
  await page.waitForFunction(() => window.__V2__?.getState().nodes.length === 1);
  assert.deepEqual((await doc()).pages[0].nodes[0].appearance, savedAppearance);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(250);
  const left = await page.locator('[data-slot="top-start"]').boundingBox();
  const right = await page.locator('[data-slot="top-end"]').boundingBox();
  assert.ok(left.x + left.width <= right.x, 'top chrome cannot overlap on narrow screens');
  const cameraControls = await page.locator('[data-slot="bottom-start"]').boundingBox();
  const creationTools = await page.locator('[data-slot="bottom-center"]').boundingBox();
  assert.ok(
    creationTools.y + creationTools.height <= cameraControls.y,
    'bottom chrome cannot overlap on narrow screens'
  );
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.waitForTimeout(250);
  await page.screenshot({ path: `${evidence}/narrow-settings.png` });
  assert.deepEqual(errors, []);
  fs.writeFileSync(`${evidence}/result.json`, JSON.stringify({ pass: true, errors, savedAppearance }, null, 2));
  console.log('V2 polish browser check passed');
} catch (error) {
  await page.screenshot({ path: `${evidence}/failure.png` });
  console.error(errors);
  throw error;
} finally { await browser.close(); }
